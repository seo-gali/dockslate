type Call<A, R> = { args: A; result: R };
type Approved = { token: string; approved: boolean };
type Id = { id: string };
type Name = { name: string };
type PathRead = Id & { path: string };
type Envelope<T> = { Ok: T; Err?: never } | { Err: string; Ok?: never };
type DockerQuery = 'engine_status' | 'overview' | 'containers_list' | 'images_list' | 'disk_usage' | 'volumes_list' | 'networks_list';
type Snapshot<C extends CommandName> = { [K in C]: Envelope<CommandResult<K>> };

