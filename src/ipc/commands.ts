export type CommandName = keyof Commands;
export type CommandArgs<C extends CommandName> = Commands[C]['args'];
export type CommandResult<C extends CommandName> = Commands[C]['result'];
export type NoArgCommand = { [C in CommandName]: CommandArgs<C> extends undefined ? C : never }[CommandName];
export type ArgCommand = Exclude<CommandName, NoArgCommand>;
