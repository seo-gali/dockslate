import fs from 'node:fs';
import {isDeepStrictEqual} from 'node:util';
import {connectNative, waitFor} from './native-verification.mjs';

const [sessionPath, baselinePath, output] = process.argv.slice(2);
if (!sessionPath || !baselinePath || !output) throw Error('Usage: node scripts/verify-wsl-recovery.mjs SESSION_JSON STOPPED_BASELINE_JSON OUTPUT_JSON');
const read = file => JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));
const session = read(sessionPath), baseline = read(baselinePath);
if (!session.isolatedProfile || baseline.initialRuntimeState !== 'stopped' || baseline.baseline.containers.some(item => ['running', 'paused', 'restarting'].includes(item.state))) throw Error('Isolated session and stopped workload baseline required');
const c = await connectNative(session.portFile);
const report = {observedAt:new Date().toISOString(), artifactSha256:session.sha256, native:true, backendInjected:false, checks:[], completed:false, globalShutdownApproved:false, compactionExecuted:false};
const fact = (value, message) => { if (!value) throw Error(message); };
const check = name => { report.checks.push({name, passed:true}); console.log(JSON.stringify({name, passed:true})); };
const rejected = async (command, args) => { let message; try { await c.invoke(command, args); } catch (failure) { message=String(failure); } fact(message, command+' unexpectedly allowed'); return message; };
const click = (selector, text) => c.evaluate(`(()=>{const button=[...document.querySelectorAll(${JSON.stringify(selector)})].find(item=>item.textContent.trim()===${JSON.stringify(text)});if(!button||button.disabled)throw Error('Button unavailable: '+${JSON.stringify(text)});button.click();})()`);
try {
  fact((await c.invoke('runtime_status')).state === 'stopped', 'Owned runtime must be stopped');
  const inventory = await c.invoke('wsl_inventory');
  const disk = inventory.disks.find(item => item.owner === 'DockSlate' && item.distribution === 'DockSlate');
  fact(disk?.path && inventory.runningDistributions.length === 0, 'Verified owned disk and no running distributions required');
  report.disk = {id:disk.id, path:disk.path, beforeBytes:disk.fileSizeBytes};
  await rejected('wsl_shutdown_preview', {diskId:'not-a-registration'});
  await rejected('wsl_shutdown', {token:'invalid-verification-token', approved:false});
  await rejected('wsl_shutdown', {token:'invalid-verification-token', approved:true});
  check('invalid target, missing approval and unknown token are rejected');
  await c.invoke('runtime_start', {approved:true});
  await waitFor('owned runtime running', async () => (await c.invoke('runtime_status')).state === 'running', 120000);
  const [containers, volumes] = await Promise.all([c.invoke('containers_list'), c.invoke('volumes_list')]);
  fact(isDeepStrictEqual(containers, baseline.baseline.containers) && isDeepStrictEqual(volumes, baseline.baseline.volumes), 'Existing workloads changed; halt verification');
  await rejected('wsl_shutdown_preview', {diskId:disk.id});
  fact((await c.invoke('runtime_status')).state === 'running', 'Read-only rejection stopped the runtime');
  check('running distribution blocks shutdown preparation without stopping it');
  await c.invoke('runtime_stop', {approved:true});
  await waitFor('owned runtime stopped', async () => (await c.invoke('runtime_status')).state === 'stopped', 120000);
  const preview = await c.invoke('wsl_preview', {diskId:disk.id});
  report.prerequisites = preview.checks;
  fact(preview.checks.some(item => ['detachedDynamicVhdx', 'exclusiveLock'].includes(item.name) && item.status !== 'passed'), 'Residual VHDX lock did not reproduce; recovery UI is unnecessary in this state');
  check('actual stopped distribution retains the VHDX lock');
  const shutdown = await c.invoke('wsl_shutdown_preview', {diskId:disk.id});
  fact(shutdown.eligible && shutdown.token && shutdown.path === disk.path && shutdown.distributions.includes('DockSlate'), 'Recovery preview must name the actual disk and distributions');
  report.shutdownPreview = {path:shutdown.path, distributions:shutdown.distributions};
  await rejected('wsl_shutdown', {token:shutdown.token, approved:false});
  await rejected('wsl_compact', {token:shutdown.token, approved:true});
  fact(!(await c.invoke('wsl_inventory')).operation, 'Shutdown token started compaction');
  check('shutdown preview is separate from approval and cannot authorize compaction');
  await c.send('Page.reload');
  await waitFor('app ready', () => c.evaluate(`!!document.querySelector('nav')||!!document.querySelector('.setup-actions button:not(:disabled)')`));
  if (await c.evaluate(`!!document.querySelector('.setup-actions')`)) await click('.setup-actions button', '설정 확인');
  await waitFor('navigation', () => c.evaluate(`!!document.querySelector('nav')`));
  await click('nav button', '디스크 관리');
  await waitFor('disk page', () => c.evaluate(`!!document.querySelector('[data-page="Disk Manager"]:not([hidden]) [role="tab"]')`));
  await click('[data-page="Disk Manager"] [role="tab"]', 'WSL 디스크');
  await waitFor('disk card', () => c.evaluate(`!!document.querySelector('[data-page="Disk Manager"] .disk-card')`));
  await click('[data-page="Disk Manager"] .disk-card button', '압축 준비 및 검사');
  await click('[data-page="Disk Manager"] .disk-inspection button', '사전 조건 검사');
  await waitFor('real recovery button', () => c.evaluate(`!![...document.querySelectorAll('[data-page="Disk Manager"] button')].find(item=>item.textContent.trim()==='WSL 가상 머신 종료…'&&!item.disabled)`));
  const start = c.calls.length;
  await click('[data-page="Disk Manager"] button', 'WSL 가상 머신 종료…');
  await waitFor('confirmation target loaded', () => c.evaluate(`!!document.querySelector('[role="dialog"] input[type="checkbox"]:not(:disabled)')`));
  const dialog = await c.evaluate(`({text:document.querySelector('[role="dialog"]').innerText,checked:document.querySelector('[role="dialog"] input').checked,disabled:document.querySelector('[role="dialog"] footer .danger-button').disabled})`);
  fact(!dialog.checked && dialog.disabled && dialog.text.includes(disk.path) && shutdown.distributions.every(name=>dialog.text.includes(name)) && dialog.text.includes('공유 WSL 가상 머신') && dialog.text.includes('압축은 별도로 승인'), 'Confirmation must disclose shared VM scope and require separate consent');
  check('real UI exposes recovery and shows disk, all distributions and separate compaction consent');
  await c.evaluate(`document.querySelector('[role="dialog"] input[type="checkbox"]').click()`);
  await waitFor('acknowledgment enables action', () => c.evaluate(`!document.querySelector('[role="dialog"] footer .danger-button').disabled`));
  await click('[role="dialog"] footer button', '취소');
  fact(!c.calls.slice(start).some(item => ['wsl_shutdown', 'wsl_compact'].includes(item.command)), 'Canceled confirmation submitted a mutation');
  check('acknowledgment enables action; cancel performs no shutdown or compaction');
  fact((await c.invoke('runtime_status')).state === 'stopped', 'Initial runtime state not restored');
  check('original stopped state restored; existing containers and volumes preserved');
  fact(c.exceptions.length === 0, 'Renderer exception');
  check('no renderer exception');
  report.completed = true;
} catch (failure) {
  report.failure = String(failure.stack ?? failure); console.error(report.failure); process.exitCode = 1;
} finally {
  fs.writeFileSync(output, JSON.stringify(report, null, 2)+'\n'); c.close();
}
