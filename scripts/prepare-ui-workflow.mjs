import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const docker=path.resolve('src-tauri/target/release/docker.exe');
const run=(...args)=>execFileSync(docker,args,{encoding:'utf8',windowsHide:true,timeout:90000}).trim();
assert.equal(run('info','--format','{{.ID}}'),'12f63594-ea3a-45f9-adf2-c594dc91cbc5');
const marker=randomUUID().replaceAll('-','');
const root=path.resolve('.analysis/file-import-fixture-ui014-'+marker);
const rows=()=>run('ps','-a','--no-trunc','--format','{{.ID}} {{.Names}} {{.State}}').split('\n').filter(Boolean).sort();
const baseline={containers:rows(),images:run('image','ls','-q','--no-trunc').split('\n').filter(Boolean),volumes:run('volume','ls','-q').split('\n').filter(Boolean).sort(),networks:run('network','ls','-q','--no-trunc').split('\n').filter(Boolean).sort()};
assert.ok(baseline.containers.some(row=>row.startsWith('3c8b6e44565e6203bd479510fab28fd14d3c57c97313aed5d44501536bc0d13e trusting_feistel exited')));
fs.mkdirSync(root);
fs.writeFileSync(path.join(root,'Dockerfile'),`FROM scratch\nLABEL dockslate.e2e.fixture="${marker}" dockslate.e2e.role="build"\nCMD ["/not-run"]\n`);
fs.writeFileSync(path.join(root,'group.Dockerfile'),`FROM scratch\nLABEL dockslate.e2e.fixture="${marker}" dockslate.e2e.role="groups"\nCMD ["/not-run"]\n`);
fs.writeFileSync(path.join(root,'compose.yaml'),'services:\n  web:\n    build:\n      context: .\n      dockerfile: Dockerfile\n');
const groupTag='dockslate-ui014-groups-'+marker.slice(0,8)+':test';
const fixture={marker,root,groupTag,baseline,createdContainers:[]};
fs.writeFileSync('.analysis/ui014-fixture.json',JSON.stringify(fixture,null,2)+'\n');
run('build','-f',path.join(root,'group.Dockerfile'),'-t',groupTag,root);
console.log(JSON.stringify({marker,root,groupTag,baselineContainers:baseline.containers,baselineVolumeCount:baseline.volumes.length}));
